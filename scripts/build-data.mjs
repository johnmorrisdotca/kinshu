// Builds src/data/currencies.data.ts from CLDR's fraction table and Kuni's country rows.
// Kuni's rows are CLDR's current tender list, plus Kosovo. Re-run after either source moves.
// Names and narrow symbols come from the ICU build in Node, which is CLDR.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const CLDR = "/Users/john/Projects/kuni/node_modules/cldr-core/supplemental/currencyData.json";
const KUNI = "/Users/john/Projects/kuni/src/data/countries.data.ts";
const OUT = new URL("../src/data/currencies.data.ts", import.meta.url);

const fractions = JSON.parse(readFileSync(CLDR, "utf8")).supplemental.currencyData.fractions;
const defaultDigits = Number(fractions.DEFAULT._digits);
const text = readFileSync(KUNI, "utf8");

/** @type {Map<string, string[]>} */
const tender = new Map();
for (const line of text.split("\n")) {
  const id = line.match(/^\s+\["([A-Z]{2})"/);
  if (id === null) continue;
  const found = line.match(/,"([A-Z]{3}(?: [A-Z]{3})*)",(?:"[a-z]{2}"|null),/);
  if (found === null) continue;
  for (const code of found[1].split(" ")) {
    const list = tender.get(code) ?? [];
    list.push(id[1]);
    tender.set(code, list);
  }
}

const english = new Intl.DisplayNames(["en"], { type: "currency" });
const japanese = new Intl.DisplayNames(["ja"], { type: "currency" });

const rows = [...tender.keys()].sort().map((code) => {
  const fraction = fractions[code] ?? {};
  const digits = Number(fraction._digits ?? defaultDigits);
  const cashDigits = fraction._cashDigits === undefined ? digits : Number(fraction._cashDigits);
  const cashRounding = fraction._cashRounding === undefined ? 0 : Number(fraction._cashRounding);
  const cashStep = cashRounding > 0 ? cashRounding : cashDigits < digits ? 10 ** (digits - cashDigits) : 1;
  let symbol = code;
  try {
    const part = new Intl.NumberFormat("en", {
      style: "currency",
      currency: code,
      currencyDisplay: "narrowSymbol",
    }).formatToParts(1).find((item) => item.type === "currency");
    if (part !== undefined) symbol = part.value;
  } catch {
    symbol = code;
  }
  return {
    code,
    en: english.of(code) ?? code,
    ja: japanese.of(code) ?? code,
    symbol,
    exponent: digits,
    cashStep,
    tender: (tender.get(code) ?? []).sort(),
  };
});

const body = rows.map((row) => {
  const tenderList = row.tender.map((code) => `"${code}"`).join(", ");
  return `  ["${row.code}", ${JSON.stringify(row.en)}, ${JSON.stringify(row.ja)}, ${JSON.stringify(row.symbol)}, ${row.exponent}, ${row.cashStep}, [${tenderList}]]`;
}).join(",\n");

const file = `// Generated by scripts/build-data.mjs. Do not edit by hand.
// Names and narrow symbols: Node's ICU, which is Unicode CLDR. Generated 2026-11-20.
// Exponent and cash step: Unicode CLDR 48 cldr-core supplemental/currencyData.json fractions.
//   cash step is CLDR cashRounding when it sets one (Canada's 5), otherwise one minor unit,
//   or a major unit when cashDigits is 0.
// Tender places: inverted from Kuni's country rows (CLDR current tender, plus Kosovo).

import type { CurrencyRow } from "../rows";

export const CURRENCY_ROWS: readonly CurrencyRow[] = [
${body},
];
`;

const outPath = fileURLToPath(OUT);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, file);
console.log(`wrote ${rows.length} currencies`);
