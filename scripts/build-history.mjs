// Builds src/data/tenures.data.ts from CLDR's region currency list.
// Each row is one spell of a currency in a country. A blank end date means CLDR
// still lists it. Re-run when cldr-core moves.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const CLDR = "/Users/john/Projects/kuni/node_modules/cldr-core/supplemental/currencyData.json";
const OUT = new URL("../src/data/tenures.data.ts", import.meta.url);

const regions = JSON.parse(readFileSync(CLDR, "utf8")).supplemental.currencyData.region;

const rows = [];
for (const country of Object.keys(regions).sort()) {
  for (const entry of regions[country]) {
    const code = Object.keys(entry)[0];
    const info = entry[code];
    rows.push({
      country,
      code,
      from: info._from ?? null,
      to: info._to ?? null,
      tender: info._tender !== "false",
    });
  }
}

rows.sort((a, b) => a.country.localeCompare(b.country) || (a.from ?? "").localeCompare(b.from ?? "") || a.code.localeCompare(b.code));

const body = rows
  .map((row) => {
    const from = row.from === null ? "null" : `"${row.from}"`;
    const to = row.to === null ? "null" : `"${row.to}"`;
    return `  ["${row.country}", "${row.code}", ${from}, ${to}, ${row.tender}]`;
  })
  .join(",\n");

const file = `// Generated by scripts/build-history.mjs. Do not edit by hand.
// Unicode CLDR 48 cldr-core supplemental/currencyData.json region list.
// A null end date means CLDR still lists the currency. "_tender": "false" is recorded as not tender.

import type { TenureRow } from "../types";

export const TENURE_ROWS: readonly TenureRow[] = [
${body},
];
`;

const outPath = fileURLToPath(OUT);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, file);
console.log(`wrote ${rows.length} tenures`);
